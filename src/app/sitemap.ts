import { MetadataRoute } from 'next';
import { headers } from 'next/headers';

export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  const headersList = await headers();
  const host = headersList.get('host') || 'localhost:3000';
  const protocol = process.env.NODE_ENV === 'production' ? 'https' : 'http';
  const baseUrl = process.env.NEXT_PUBLIC_APP_URL || `${protocol}://${host}`;

  const routes = [
    '',
    '/movies',
    '/tv',
    '/trending',
    '/box-office',
    '/top-rated',
    '/upcoming',
    '/now-playing',
    '/popular-people',
    '/collections',
    '/companies',
    '/genres',
    '/certifications',
    '/languages',
    '/reviews',
    '/watch-analytics',
    '/keywords',
    '/airing-today',
    '/on-the-air',
    '/networks',
    '/changes',
    '/providers',
    '/discover',
    '/search',
    '/watchlist',
    '/api-explorer',
    '/ai-recommendations',
    '/compare',
    '/decade',
    '/random',
    '/trivia',
    '/history',
    '/soundtracks',
    '/cinematography',
    '/animation',
    '/oscar-winners',
    '/anime',
    '/documentaries',
    '/cult-classics',
    '/box-office-predictor',
    '/ratings-matrix',
    '/countries',
    '/directors',
    '/tropes',
    '/filmography',
    '/box-office-analytics',
    '/release-calendar',
    '/studios',
    '/sub-genres',
    '/timezones',
    '/jobs',
    '/countries-catalog',
    '/primary-translations',
    '/guest-sessions',
    '/festivals',
    '/eras',
    '/auteurs',
    '/scores',
    '/leaderboard',
    '/streaming-matrix',
    '/audio-formats',
    '/quotes',
  ];

  return routes.map((route) => ({
    url: `${baseUrl}${route}`,
    lastModified: new Date(),
    changeFrequency: 'daily',
    priority: route === '' ? 1.0 : 0.8,
  }));
}
